#!/usr/bin/env python3
"""Write tests/vectors.h from the Python reference implementation (RNS).

Run with an interpreter that has rns and cbor2:  python3 tests/gen_vectors.py
"""
import hashlib
import hmac
import os
import sys

import cbor2
import RNS
from RNS.Cryptography import hkdf
from RNS.Cryptography.Token import Token
from RNS.Cryptography.AES import AES_256_CBC
from RNS.Cryptography import PKCS7


def c_bytes(name, data):
    body = ", ".join("0x%02x" % b for b in data)
    return "static const uint8_t %s[%d] = { %s };\n" % (name, len(data), body)


out = ["/* Generated by tests/gen_vectors.py from RNS %s. Do not edit. */\n" % RNS.__version__ if hasattr(RNS, "__version__") else "/* Generated by tests/gen_vectors.py. Do not edit. */\n", "#include <stdint.h>\n"]

prv = bytes(range(1, 65))
ident = RNS.Identity.from_bytes(prv)
out.append(c_bytes("V_ID_PRV", prv))
out.append(c_bytes("V_ID_PUB", ident.get_public_key()))
out.append(c_bytes("V_ID_HASH", ident.hash))

out.append(c_bytes("V_HUB_DEST", RNS.Destination.hash(ident, "rrc", "hub")))
out.append(c_bytes("V_PR_DEST", RNS.Destination.hash(None, "rnstransport", "path", "request")))

msg = b"weechat-rrc test message"
out.append(c_bytes("V_SIG_MSG", msg))
out.append(c_bytes("V_SIG", ident.sign(msg)))

peer = RNS.Identity.from_bytes(bytes(range(100, 164)))
shared = ident.prv.exchange(peer.pub)
out.append(c_bytes("V_PEER_XPUB", peer.get_public_key()[:32]))
out.append(c_bytes("V_SHARED", shared))

salt = bytes(range(16))
out.append(c_bytes("V_HKDF_SALT", salt))
out.append(c_bytes("V_HKDF_OUT", hkdf(length=64, derive_from=shared, salt=salt, context=None)))
out.append(c_bytes("V_HKDF_NOSALT", hkdf(length=64, derive_from=shared, salt=None, context=None)))

key = bytes(range(200, 256)) + bytes(range(8))
plain = b"a plaintext that spans more than one AES block"
token = Token(key).encrypt(plain)
out.append(c_bytes("V_TOKEN_KEY", key))
out.append(c_bytes("V_TOKEN_PLAIN", plain))
out.append(c_bytes("V_TOKEN", token))
iv = bytes(16)
ct = AES_256_CBC.encrypt(plaintext=PKCS7.pad(plain), key=key[32:], iv=iv)
fixed = iv + ct + hmac.new(key[:32], iv + ct, hashlib.sha256).digest()
out.append(c_bytes("V_TOKEN_FIXED_IV", fixed))

env = {0: 1, 1: 20, 2: b"\x01" * 8, 3: 1737849600000, 4: ident.hash,
       5: "lobby", 6: "hello é █", 7: "funkpower"}
out.append(c_bytes("V_CBOR_ENV", cbor2.dumps(env)))
welcome = {0: 1, 1: 2, 2: b"\x02" * 8, 3: 1737849600000, 4: peer.hash,
           6: {0: "testhub", 1: "0.3.2", 2: {0: True, 1: True}, 3: {0: 32, 1: 64, 2: 350, 3: 32, 4: 240}}}
out.append(c_bytes("V_CBOR_WELCOME", cbor2.dumps(welcome)))

sys.stdout.write("".join(out))
